"""Agent command lines, their environment and their human-readable forms.

Everything a scheduled run executes is decided here from three inputs: the stored job, the
LEVELS table in edition.py and the executable identity resolved by identity.py. The prompt is
never part of any argv or environment built here; every CLI reads it from stdin, which the
supervisor closes after writing.
"""

import os
import pwd
import re
import shlex

from . import consts, edition, fsio, identity, jobs
from .errors import ApError

_LANG_RE = re.compile(r"^[A-Za-z0-9_.@-]{1,64}$")
_USER_RE = re.compile(r"^[A-Za-z0-9._][A-Za-z0-9._-]{0,63}$")
_XDG_HOMES = ("XDG_CONFIG_HOME", "XDG_DATA_HOME", "XDG_STATE_HOME", "XDG_CACHE_HOME")
# Cursor picks its config folder (and so its sign-in) from XDG_CONFIG_HOME: copied exactly or left unset.
_CURSOR_XDG = ("XDG_CONFIG_HOME", "XDG_DATA_HOME")
_PATH_VALUE_MAX = 1024
_SESSION_PATH_MAX = 4096
_GIT_WALK_MAX = 64
_SYSTEM_PATH = "/usr/bin:/bin"
# Harnesses whose new sessions get an id generated by the helper when the job is stored.
NEW_SESSION_HARNESSES = ("claude", "gemini", "pi")


def _level_entry(harness, level_id):
    entry = edition.level(level_id)
    if entry is None:
        raise ApError("invalid_level", field="level")
    per = entry["harness"].get(harness)
    if per is None:
        if harness in consts.HARNESSES:
            raise ApError("level_unavailable", field="level")
        raise ApError("invalid_harness", field="harness")
    return entry, per


def _clean_abs(value):
    if not isinstance(value, str) or not value.startswith("/"):
        return None
    if len(value.encode("utf-8", "surrogateescape")) > _PATH_VALUE_MAX:
        return None
    if "\x00" in value or "\n" in value:
        return None
    return value


def _user_name(key):
    value = os.environ.get(key, "")
    if _USER_RE.match(value):
        return value
    try:
        name = pwd.getpwuid(os.getuid()).pw_name
    except KeyError:
        return None
    return name if _USER_RE.match(name) else None


def _lang():
    lang = os.environ.get("LANG", "")
    return lang if _LANG_RE.match(lang) else "C.UTF-8"


def _add_users(env):
    for key in ("USER", "LOGNAME"):
        name = _user_name(key)
        if name is not None:
            env[key] = name


def _add_runtime(env):
    runtime = os.environ.get("XDG_RUNTIME_DIR", "")
    if fsio.runtime_dir_valid(runtime):
        env["XDG_RUNTIME_DIR"] = runtime


def agent_env(harness, level_id):
    """Allowlisted environment for an agent child (R0 D11, v2 section 5).

    Credentials in the environment (API keys, OAuth tokens) would switch the CLI to API
    billing or to another account, and display variables would let a headless run reach the
    desktop, so nothing outside this list is ever copied from the runner's environment.
    """
    if harness not in consts.HARNESSES:
        raise ApError("invalid_harness", field="harness")
    _entry, per = _level_entry(harness, level_id)
    home = fsio.home()
    env = {"HOME": home}
    if harness == "pi":
        # Pi finds its sign-in store from HOME alone; the auth check and the run must see the same one.
        env.update(PATH=_SYSTEM_PATH, LANG=_lang(), TERM="dumb")
    elif harness == "cursor":
        _add_users(env)
        _add_runtime(env)
        for key in _CURSOR_XDG:
            value = _clean_abs(os.environ.get(key, ""))
            if value is not None:
                env[key] = value
        # The cursor-agent wrapper calls coreutils through PATH.
        env.update(LANG=_lang(), TERM="dumb", NO_COLOR="1", PATH=_SYSTEM_PATH)
    else:
        _add_users(env)
        _add_runtime(env)
        bus = os.environ.get("DBUS_SESSION_BUS_ADDRESS", "")
        if bus and len(bus) <= _PATH_VALUE_MAX and bus.isprintable():
            env["DBUS_SESSION_BUS_ADDRESS"] = bus
        for key in _XDG_HOMES:
            value = _clean_abs(os.environ.get(key, ""))
            if value is not None:
                env[key] = value
        env["LANG"] = _lang()
        env["NO_COLOR"] = "1"
        env["TERM"] = "dumb"
        env["PATH"] = "/usr/bin:/bin:" + home + "/.local/bin"
    for key, value in per["env"].items():
        env[key] = value
    return env


def _session_grammar(harness):
    return consts.OPENCODE_ID_RE if harness == "opencode" else consts.UUID_RE


def effective_session(job):
    """(mode, session id) the next run uses: a stored runSessionId always means resume."""
    target = job["target"]
    run_sid = (job.get("state") or {}).get("runSessionId")
    if run_sid:
        return "resume", run_sid
    mode = target["mode"]
    if mode == "new":
        return "new", target.get("newSessionId")
    return mode, target.get("sessionId")


def effective_session_path(job):
    """Pi only: the session file the next run opens (the run's own session first), else None."""
    if job.get("harness") != "pi":
        return None
    state = job.get("state") or {}
    target = job.get("target") or {}
    return state.get("runSessionPath") or target.get("sessionPath")


def pi_session_path_ok(path):
    """An absolute, normalized .jsonl path exactly one folder below ~/.pi/agent/sessions."""
    if not isinstance(path, str) or not path.startswith("/") or "\x00" in path or "\n" in path:
        return False
    try:
        if len(path.encode("utf-8")) > _SESSION_PATH_MAX:
            return False
    except UnicodeEncodeError:
        return False
    if not path.endswith(".jsonl") or os.path.normpath(path) != path:
        return False
    root = fsio.home().rstrip("/") + "/" + consts.PI_SESSIONS_REL
    roots = {root + "/", os.path.realpath(root) + "/"}
    for prefix in roots:
        if path.startswith(prefix):
            rest = path[len(prefix):]
            return rest.count("/") == 1 and not rest.startswith("/") and "/" != rest[-1:]
    return False


def write_session(job):
    """Session id a run writes into, or None when the CLI creates a fresh one (fork, new)."""
    mode, sid = effective_session(job)
    if mode == "resume":
        return sid
    if mode == "new":
        return sid or None
    return None


def _budget_text(value):
    return ("%.2f" % float(value)).rstrip("0").rstrip(".")


def _model_ok(model):
    """The v2 model grammar, or the v1 grammar a stored job may still carry."""
    return jobs.model_ok(model) or (isinstance(model, str) and consts.MODEL_RE_V1.fullmatch(model) is not None)


# A preview of a draft that is not stored yet has no job id and, for a new Claude, Gemini or Pi
# session, no pre-assigned session id (job-create generates both). The preview shows these
# placeholders instead; neither value is part of the command digest.
PREVIEW_JOB_ID = "<job>"
PREVIEW_NEW_SESSION = "<new-session-id>"


def _check_ids(job, harness, mode, sid, preview):
    grammar = _session_grammar(harness)
    if mode in ("resume", "fork"):
        if not isinstance(sid, str) or not grammar.match(sid):
            raise ApError("invalid_session", field="target.sessionId")
    if mode == "fork" and not consts.CAN_FORK.get(harness, False):
        raise ApError("fork_unsupported", field="target.mode")
    if mode == "new" and harness in NEW_SESSION_HARNESSES and not (preview and sid is None):
        if not isinstance(sid, str) or not consts.UUID_RE.match(sid):
            raise ApError("invalid_session", field="target.newSessionId")
    job_id = job.get("id")
    if not (isinstance(job_id, str) and consts.JOB_ID_RE.match(job_id)) and not (preview and job_id is None):
        raise ApError("bad_input", field="id")


def _build(job, exec_prefix, run_dir, gen_text, preview=False):
    harness = job["harness"]
    if harness not in consts.HARNESSES:
        raise ApError("invalid_harness", field="harness")
    _entry, per = _level_entry(harness, job["level"])
    target = job["target"]
    cwd = target.get("cwd")
    if _clean_abs(cwd) is None:
        raise ApError("invalid_cwd", field="target.cwd")
    model = job.get("model")
    if model is not None and not _model_ok(model):
        raise ApError("invalid_model", field="model")
    mode, sid = effective_session(job)
    _check_ids(job, harness, mode, sid, preview)
    if not exec_prefix or not all(isinstance(p, str) and p.startswith("/") for p in exec_prefix):
        raise ApError("cli_untrusted")
    level_argv = list(per["argv"])
    id8 = job["id"][:8] if job.get("id") else PREVIEW_JOB_ID
    if mode == "new" and sid is None:
        sid = PREVIEW_NEW_SESSION
    argv = list(exec_prefix)

    if harness == "claude":
        argv += ["-p", "--output-format", "stream-json", "--verbose"]
        slot = [len(argv), len(argv) + len(level_argv)]
        argv += level_argv
        limits = job["limits"]
        argv += ["--max-turns", str(int(limits["maxTurns"]))]
        # The dollar cap only exists for a job that may spend dollars at all.
        if job.get("allowPaid") is True:
            argv += ["--max-budget-usd", _budget_text(limits["budgetUsd"])]
        if model:
            argv += ["--model", model]
        if mode == "resume":
            argv += ["--resume", sid]
        elif mode == "fork":
            argv += ["--resume", sid, "--fork-session"]
        else:
            argv += ["--session-id", sid, "--name", edition.SESSION_NAME_PREFIX + id8]
    elif harness == "opencode":
        argv += ["run", "--dir", cwd, "--format", "json"]
        slot = [len(argv), len(argv) + len(level_argv)]
        argv += level_argv
        if model:
            argv += ["-m", model]
        if mode == "resume":
            argv += ["-s", sid]
        elif mode == "fork":
            argv += ["-s", sid, "--fork"]
        else:
            argv += ["--title", edition.SESSION_NAME_PREFIX + id8]
    elif harness == "codex":
        argv += ["exec", "-C", cwd]
        slot = [len(argv), len(argv) + len(level_argv)]
        argv += level_argv
        argv += ["--json", "--color", "never", "-o", run_dir + "/" + job["id"] + "-g" + gen_text + ".last.txt"]
        if target.get("allowNonGit") is True:
            argv += ["--skip-git-repo-check"]
        if model:
            argv += ["-m", model]
        if mode == "resume":
            argv += ["resume", sid, "-"]
        elif mode == "fork":
            argv += ["fork", sid, "-"]
        else:
            argv += ["-"]
    elif harness == "gemini":
        argv += ["-p", "", "-o", "json"]
        slot = [len(argv), len(argv) + len(level_argv)]
        argv += level_argv
        if model:
            argv += ["-m", model]
        if mode == "resume":
            argv += ["--resume", sid]
        else:
            argv += ["--session-id", sid]
    elif harness == "cursor":
        if model == "auto":
            raise ApError("invalid_model", field="model")
        argv += ["-p", "--output-format", "stream-json"]
        slot = [len(argv), len(argv) + len(level_argv)]
        argv += level_argv
        argv += ["--workspace", cwd]
        if model:
            argv += ["--model", model]
        if mode == "resume":
            argv += ["--resume", sid]
    elif harness == "pi":
        provider = job.get("provider")
        if not (isinstance(provider, str) and consts.PI_PROVIDER_RE.fullmatch(provider)):
            raise ApError("pi_model_required", field="provider")
        if not model:
            raise ApError("pi_model_required", field="model")
        argv += ["--mode", "json"]
        slot = [len(argv), len(argv) + len(level_argv)]
        argv += level_argv
        argv += ["--provider", provider, "--model", model]
        if mode == "new":
            argv += ["--session-id", sid, "--name", edition.SESSION_NAME_PREFIX + id8]
        else:
            # Only absolute in-store paths: a partial id can match another project's session, whose
            # confirmation question would read the prompt from stdin.
            path = effective_session_path(job) if mode == "resume" else target.get("sessionPath")
            if not pi_session_path_ok(path):
                raise ApError("invalid_session", field="target.sessionPath")
            argv += ["--session", path] if mode == "resume" else ["--fork", path]
    else:
        raise ApError("invalid_harness", field="harness")

    env = agent_env(harness, job["level"])
    return {"argv": argv, "env": env, "cwd": cwd, "levelSlot": slot, "mode": mode}


def build_command(job, *, exec_prefix, run_dir, gen):
    """Exact agent argv, environment and cwd for one run (contract 3.6, v2 section 5)."""
    if not isinstance(gen, int) or isinstance(gen, bool) or gen < 1:
        raise ApError("bad_args")
    if _clean_abs(run_dir) is None:
        raise ApError("state_refused")
    built = _build(job, exec_prefix, run_dir, str(gen))
    return {"argv": built["argv"], "env": built["env"], "cwd": built["cwd"], "levelSlot": built["levelSlot"]}


def display_argv(harness, argv, exec_len):
    """One-line form of an argv for the "Will run" line: CLI name, arguments, then <stdin>."""
    parts = [consts.CLI_NAMES.get(harness, "agent")]
    for arg in argv[exec_len:]:
        if arg == "":
            parts.append('""')
        elif any(ch.isspace() for ch in arg) or "'" in arg:
            parts.append(shlex.quote(arg))
        else:
            parts.append(arg)
    parts.append("<stdin>")
    return " ".join(parts)


def _inside_git(path):
    current = path
    for _ in range(_GIT_WALK_MAX):
        if os.path.lexists(os.path.join(current, ".git")):
            return True
        parent = os.path.dirname(current)
        if parent == current:
            return False
        current = parent
    return False


def preview_command(job):
    """Preview (contract 4.6) of what a run would execute with the CLI discovered now.

    Raises cli_missing or cli_untrusted when the CLI cannot be used; the fire-time fields
    (fireAt, immediate, fireAtHint, fireAtError) are left empty for the caller to fill, and
    cli_core adds the paid-usage gate.
    """
    harness = job["harness"]
    found = identity.discover_cli(harness)
    if not found["ok"]:
        raise ApError("cli_missing" if found["reason"] == "not_found" else "cli_untrusted")
    shown = dict(job)
    cli = dict(job.get("cli") or {})
    cli["link"] = found["link"]
    cli["real"] = found["real"]
    shown["cli"] = cli
    _entry, per = _level_entry(harness, job["level"])
    built = _build(shown, found["exec"], "<runs>", "<gen>", preview=True)
    warnings = []
    if harness == "codex" and job["target"].get("allowNonGit") is not True and not _inside_git(built["cwd"]):
        warnings.append("non_git_dir")
    return {
        "harness": harness,
        "level": job["level"],
        "mode": built["mode"],
        "display": display_argv(harness, built["argv"], len(found["exec"])),
        "argv": built["argv"],
        "env": dict(per["env"]),
        "cwd": built["cwd"],
        "binary": found["real"],
        "link": found["link"],
        "version": cli.get("version"),
        "levelCaption": per["caption"],
        "commandDigest": jobs.command_digest(shown),
        "fireAt": None,
        "immediate": False,
        "fireAtHint": None,
        "fireAtError": None,
        "warnings": warnings,
    }


def resume_display(job):
    """Terminal command that reopens the job's session, for "Copy resume command"."""
    harness = job["harness"]
    state = job.get("state") or {}
    sid = state.get("runSessionId") or job["target"].get("sessionId")
    if not isinstance(sid, str) or not _session_grammar(harness).match(sid):
        raise ApError("bad_status")
    cwd = job["target"].get("cwd")
    if _clean_abs(cwd) is None:
        raise ApError("bad_status")
    prefix = "cd " + shlex.quote(cwd) + " && "
    if harness == "claude":
        return prefix + "claude --resume " + sid
    if harness == "opencode":
        return prefix + "opencode --session " + sid
    if harness == "codex":
        return prefix + "codex resume " + sid
    if harness == "cursor":
        return prefix + consts.CLI_NAMES["cursor"] + " --resume " + sid
    if harness == "pi":
        path = effective_session_path(job)
        if not pi_session_path_ok(path):
            raise ApError("bad_status")
        return prefix + "pi --session " + shlex.quote(path)
    return prefix + "gemini --resume " + sid
