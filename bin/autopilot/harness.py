def gemini_policy_path():
    """The admin policy a Gemini CLI job is started with (GEMINI_POLICY_REL in the plugin)."""
    return os.path.join(fsio.plugin_dir(), GEMINI_POLICY_REL)


def gemini_policy_wanted(level_id):
    """Whether a Gemini CLI job at level_id runs under the admin policy: every level but the ones
    the edition exempts (edition.GEMINI_POLICY_EXEMPT_LEVELS; none when it names none)."""
    return level_id not in getattr(edition, "GEMINI_POLICY_EXEMPT_LEVELS", ())


def _level_entry(harness, level_id):
    entry = edition.level(level_id)
    if entry is None:
        raise ApError("invalid_level", field="level")
    per = entry["harness"].get(harness)
    if per is None:
        if harness in consts.HARNESSES:
            raise ApError("level_unavailable", field="level")
        raise ApError("invalid_harness", field="harness")
    return entry, per


def _clean_abs(value):
    if not isinstance(value, str) or not value.startswith("/"):
        return None
    if len(value.encode("utf-8", "surrogateescape")) > _PATH_VALUE_MAX:
        return None
    if "\x00" in value or "\n" in value:
        return None
    return value


def _user_name(key):
    value = os.environ.get(key, "")
    if _USER_RE.match(value):
        return value
    try:
        name = pwd.getpwuid(os.getuid()).pw_name
    except KeyError:
        return None
    return name if _USER_RE.match(name) else None


def _lang():
    lang = os.environ.get("LANG", "")
    return lang if _LANG_RE.match(lang) else "C.UTF-8"


def _add_users(env):
    for key in ("USER", "LOGNAME"):
        name = _user_name(key)
        if name is not None:
            env[key] = name


def _add_runtime(env):
    runtime = os.environ.get("XDG_RUNTIME_DIR", "")
    if fsio.runtime_dir_valid(runtime):
        env["XDG_RUNTIME_DIR"] = runtime


def claude_level_tools(harness_id, level_id):
    """The tool names a Claude level offers through --tools, or None when it names none."""
    entry = edition.level(level_id)
    argv = entry["harness"].get(harness_id, {}).get("argv", []) if entry is not None and harness_id == "claude" else []
    if "--tools" in argv and argv.index("--tools") + 1 < len(argv):
        return tuple(argv[argv.index("--tools") + 1].split(","))
    return None


def agent_env(harness, level_id):
    """Allowlisted environment for an agent child (R0 D11, v2 section 5).

    Credentials in the environment (API keys, OAuth tokens) would switch the CLI to API
    billing or to another account, and display variables would let a headless run reach the
    desktop, so nothing outside this list is ever copied from the runner's environment.
    """
    if harness not in consts.HARNESSES:
        raise ApError("invalid_harness", field="harness")
    _entry, per = _level_entry(harness, level_id)
    home = fsio.home()
    env = {"HOME": home}
    if harness == "pi":
        # Pi finds its sign-in store from HOME alone; the auth check and the run must see the same one.
        env.update(PATH=_SYSTEM_PATH, LANG=_lang(), TERM="dumb")
    elif harness == "cursor":
        _add_users(env)
        _add_runtime(env)
        for key in _CURSOR_XDG:
            value = _clean_abs(os.environ.get(key, ""))
            if value is not None:
                env[key] = value
        # The cursor-agent wrapper calls coreutils through PATH.
        env.update(LANG=_lang(), TERM="dumb", NO_COLOR="1", PATH=_SYSTEM_PATH)
    else:
        _add_users(env)
        _add_runtime(env)
        bus = os.environ.get("DBUS_SESSION_BUS_ADDRESS", "")
        if bus and len(bus) <= _PATH_VALUE_MAX and bus.isprintable():
            env["DBUS_SESSION_BUS_ADDRESS"] = bus
        for key in _XDG_HOMES:
            value = _clean_abs(os.environ.get(key, ""))
            if value is not None:
                env[key] = value
        env["LANG"] = _lang()
        env["NO_COLOR"] = "1"
        env["TERM"] = "dumb"
        env["PATH"] = "/usr/bin:/bin:" + home + "/.local/bin"
    for key, value in per["env"].items():
        env[key] = value
    if harness == "opencode":
        # Project config is never loaded for a headless run: an opencode.json or a file under
        # .opencode could redefine the agent, its permissions, its MCP servers or its tools and
        # undo the level. The folder's own plugin code is refused separately (jobs.cwd_verdict),
        # because this flag does not stop it.
        env["OPENCODE_DISABLE_PROJECT_CONFIG"] = "1"
    return env


def _session_grammar(harness):
    return consts.OPENCODE_ID_RE if harness == "opencode" else consts.UUID_RE


def effective_session(job):
    """(mode, session id) the next run uses: a stored runSessionId always means resume."""
    target = job["target"]
    run_sid = (job.get("state") or {}).get("runSessionId")
    if run_sid:
        return "resume", run_sid
    mode = target["mode"]
    if mode == "new":
        return "new", target.get("newSessionId")
    return mode, target.get("sessionId")


def effective_session_path(job):
    """Pi only: the session file the next run opens (the run's own session first), else None."""
    if job.get("harness") != "pi":
        return None
    state = job.get("state") or {}
    target = job.get("target") or {}
    return state.get("runSessionPath") or target.get("sessionPath")


def pi_session_path_ok(path):
    """An absolute, normalized .jsonl path exactly one folder below ~/.pi/agent/sessions."""
    if not isinstance(path, str) or not path.startswith("/") or "\x00" in path or "\n" in path:
        return False
    try:
        if len(path.encode("utf-8")) > _SESSION_PATH_MAX:
            return False
    except UnicodeEncodeError:
        return False
    if not path.endswith(".jsonl") or os.path.normpath(path) != path:
        return False
    root = fsio.home().rstrip("/") + "/" + consts.PI_SESSIONS_REL
    roots = {root + "/", os.path.realpath(root) + "/"}
    for prefix in roots:
        if path.startswith(prefix):
            rest = path[len(prefix):]
            return rest.count("/") == 1 and not rest.startswith("/") and "/" != rest[-1:]
    return False


def _pi_default_dir(cwd):
    """The folder Pi files a working folder's sessions in (its getDefaultSessionDir)."""
    relative = cwd[1:] if cwd.startswith("/") else cwd
    return (fsio.home().rstrip("/") + "/" + consts.PI_SESSIONS_REL + "/--"
            + re.sub(r"[/\\:]", "-", relative) + "--")


def _pi_id_unique(session_id, path):
    """True when path is the one session file in the store named after session_id."""
    pattern = os.path.join(glob.escape(fsio.home()), consts.PI_SESSIONS_REL, "*", "*_" + session_id + ".jsonl")
    try:
        found = [os.path.realpath(p) for p in glob.glob(pattern)]
    except OSError:
        return False
    return found == [os.path.realpath(path)]


def write_session(job):
    """Session id a run writes into, or None when the CLI creates a fresh one (fork, new)."""
    mode, sid = effective_session(job)
    if mode == "resume":
        return sid
    if mode == "new":
        return sid or None
    return None


def _budget_text(value):
    return ("%.2f" % float(value)).rstrip("0").rstrip(".")


def _model_ok(model):
    """The v2 model grammar, or the v1 grammar a stored job may still carry."""
    return jobs.model_ok(model) or (isinstance(model, str) and consts.MODEL_RE_V1.fullmatch(model) is not None)


# A preview of a draft that is not stored yet has no job id and, for a new Claude, Gemini or Pi
# session, no pre-assigned session id (job-create generates both). The preview shows these
# placeholders instead; neither value is part of the command digest.
PREVIEW_JOB_ID = "<job>"
PREVIEW_NEW_SESSION = "<new-session-id>"


def _check_ids(job, harness, mode, sid, preview):
    grammar = _session_grammar(harness)
    if mode in ("resume", "fork"):
        if not isinstance(sid, str) or not grammar.fullmatch(sid):
            raise ApError("invalid_session", field="target.sessionId")
    if mode == "fork" and not consts.CAN_FORK.get(harness, False):
        raise ApError("fork_unsupported", field="target.mode")
    if mode == "new" and harness in NEW_SESSION_HARNESSES and not (preview and sid is None):
        if not isinstance(sid, str) or not consts.UUID_RE.fullmatch(sid):
            raise ApError("invalid_session", field="target.newSessionId")
    job_id = job.get("id")
    if not (isinstance(job_id, str) and consts.JOB_ID_RE.fullmatch(job_id)) and not (preview and job_id is None):
        raise ApError("bad_input", field="id")


def _build(job, exec_prefix, run_dir, gen_text, preview=False):
    harness = job["harness"]
    if harness not in consts.HARNESSES:
        raise ApError("invalid_harness", field="harness")
    _entry, per = _level_entry(harness, job["level"])
    target = job["target"]
    cwd = target.get("cwd")
    if _clean_abs(cwd) is None:
        raise ApError("invalid_cwd", field="target.cwd")
    model = job.get("model")
    if model is not None and not _model_ok(model):
        raise ApError("invalid_model", field="model")
    mode, sid = effective_session(job)
    _check_ids(job, harness, mode, sid, preview)
    if not exec_prefix or not all(isinstance(p, str) and p.startswith("/") for p in exec_prefix):
        raise ApError("cli_untrusted")
    level_argv = list(per["argv"])
    id8 = job["id"][:8] if job.get("id") else PREVIEW_JOB_ID
    if mode == "new" and sid is None:
        sid = PREVIEW_NEW_SESSION
    argv = list(exec_prefix)
    pi_env = {}

    if harness == "claude":
        argv += ["-p", "--output-format", "stream-json", "--verbose"]
        slot = [len(argv), len(argv) + len(level_argv)]
        argv += level_argv
        limits = job["limits"]
        argv += ["--max-turns", str(int(limits["maxTurns"]))]
        # The dollar cap only exists for a job that may spend dollars at all.
        if job.get("allowPaid") is True:
            argv += ["--max-budget-usd", _budget_text(limits["budgetUsd"])]
        if model:
            argv += ["--model", model]
        if mode == "resume":
            argv += ["--resume", sid]
        elif mode == "fork":
            argv += ["--resume", sid, "--fork-session"]
        else:
            argv += ["--session-id", sid, "--name", edition.SESSION_NAME_PREFIX + id8]
    elif harness == "opencode":
        # No --dir: the agent is started in the working folder (cmd["cwd"]), which is what
        # opencode, Codex and Cursor Agent use when no folder is named, and a folder named on
        # the command line is readable by every account on the computer.
        argv += ["run", "--format", "json"]
        slot = [len(argv), len(argv) + len(level_argv)]
        argv += level_argv
        if model:
            argv += ["-m", model]
        if mode == "resume":
            argv += ["-s", sid]
        elif mode == "fork":
            argv += ["-s", sid, "--fork"]
        else:
            argv += ["--title", edition.SESSION_NAME_PREFIX + id8]
    elif harness == "codex":
        argv += ["exec"]
        # Drop the execpolicy allow rules in ~/.codex/rules and in a trusted folder: a command that
        # matches one otherwise runs outside the sandbox. The rules name no folder, so this flag
        # does not put one on the command line. (A folder's own trust, which would load its
        # .codex/config.toml, is keyed by path and cannot be pinned without naming the folder on
        # the command line, which this plugin never does; -s still fixes the sandbox mode itself.)
        argv += ["--ignore-rules"]
        slot = [len(argv), len(argv) + len(level_argv)]
        argv += level_argv
        argv += ["--json", "--color", "never", "-o", run_dir + "/" + job["id"] + "-g" + gen_text + ".last.txt"]
        if target.get("allowNonGit") is True:
            argv += ["--skip-git-repo-check"]
        if model:
            argv += ["-m", model]
        if mode == "resume":
            argv += ["resume", sid, "-"]
        elif mode == "fork":
            argv += ["fork", sid, "-"]
        else:
            argv += ["-"]
    elif harness == "gemini":
        argv += ["-p", "", "-o", "json"]
        slot = [len(argv), len(argv) + len(level_argv)]
        argv += level_argv
        if gemini_policy_wanted(job["level"]):
            argv += ["--admin-policy", gemini_policy_path()]
        if model:
            argv += ["-m", model]
        if mode == "resume":
            argv += ["--resume", sid]
        else:
            argv += ["--session-id", sid]
    elif harness == "cursor":
        if model == "auto":
            raise ApError("invalid_model", field="model")
        argv += ["-p", "--output-format", "stream-json"]
        slot = [len(argv), len(argv) + len(level_argv)]
        argv += level_argv
        if model:
            argv += ["--model", model]
        if mode == "resume":
            argv += ["--resume", sid]
    elif harness == "pi":
        provider = job.get("provider")
        if not (isinstance(provider, str) and consts.PI_PROVIDER_RE.fullmatch(provider)):
            raise ApError("pi_model_required", field="provider")
        if not model:
            raise ApError("pi_model_required", field="model")
        argv += ["--mode", "json"]
        slot = [len(argv), len(argv) + len(level_argv)]
        argv += level_argv
        argv += ["--provider", provider, "--model", model]
        if mode == "new":
            argv += ["--session-id", sid, "--name", edition.SESSION_NAME_PREFIX + id8]
            # Pin where the new session is filed, so a folder's own .pi/settings.json sessionDir
            # cannot send the transcript, with the file contents it read, somewhere the repo chose.
            pi_env["PI_CODING_AGENT_SESSION_DIR"] = _pi_default_dir(os.path.realpath(cwd))
        else:
            path = effective_session_path(job) if mode == "resume" else target.get("sessionPath")
            if not pi_session_path_ok(path):
                raise ApError("invalid_session", field="target.sessionPath")
            if not path.endswith("_" + sid + ".jsonl"):
                raise ApError("invalid_session", field="target.sessionId")
            # The session goes by its full id, and the folder Pi looks it up in goes in the
            # environment. Its path would name the project: Pi files sessions in a folder named
            # after the working folder, and a command line is readable by every account.
            # An id Pi does not find in that folder is looked up in every project, and for
            # --session a match there is a question read from stdin, which holds the prompt.
            # So a resume points Pi at the folder its file is in. A fork's new file goes into
            # the folder named, so that is the one Pi itself uses for the working folder (and
            # the one classify derives from the header the run prints); the source is found
            # there, or else by its id across the store, where --fork asks nothing.
            if mode == "resume":
                pi_dir = os.path.dirname(path)
            else:
                pi_dir = _pi_default_dir(os.path.realpath(cwd))
                # Found in that folder unless the working folder is reached through a link; then
                # Pi searches by id, which must name this one file.
                if os.path.dirname(path) != pi_dir and not _pi_id_unique(sid, path):
                    raise ApError("invalid_session", field="target.sessionId")
            argv += ["--session", sid] if mode == "resume" else ["--fork", sid]
            pi_env["PI_CODING_AGENT_SESSION_DIR"] = pi_dir
    else:
        raise ApError("invalid_harness", field="harness")

    env = agent_env(harness, job["level"])
    env.update(pi_env)
    spec = sandbox_spec(harness, job["level"], cwd, env, exec_prefix, run_dir)
    if spec is not None:
        env.update(spec["env"])
    return {"argv": argv, "env": env, "cwd": cwd, "levelSlot": slot, "mode": mode, "confine": spec}


# --- Auto-level OS confinement (Unlocked) ------------------------------------------------------

# At Auto the shell is on, so the agent process is confined with Landlock and a seccomp filter
# (see confine.py). Only these agents are sandboxed at Auto: Codex has its own sandbox and Claude
# its classifier, and Full is unrestricted by design.
SANDBOX_AGENTS = ("opencode", "gemini", "pi")
SANDBOX_LEVEL = "auto"
# Read-only for every sandboxed run: the system, and the folders agents and toolchains live in.
# A missing one is skipped. Nothing under the home folder is readable unless named below, so a
# secret folder (~/.ssh, ~/.gnupg, another tool's token) is never granted.
_SANDBOX_SYS_RO = ("/usr", "/bin", "/sbin", "/lib", "/lib64", "/lib32", "/libx32", "/opt",
                   "/etc", "/proc", "/run", "/dev")
# The device nodes a shell and its tools write to (RO /dev would break bash and git).
_SANDBOX_DEV_FILES = ("/dev/null", "/dev/zero", "/dev/full", "/dev/random", "/dev/urandom", "/dev/tty")


def _xdg_dir(env, key, rel, home):
    value = _clean_abs(env.get(key, ""))
    return value if value is not None else os.path.join(home, rel)


def sandbox_wanted(harness, level_id):
    """True when a run of this agent at this level is confined (Unlocked Auto, OS sandbox agents)."""
    return level_id == SANDBOX_LEVEL and harness in SANDBOX_AGENTS


def sandbox_spec(harness, level_id, cwd, env, exec_prefix, run_dir):
    """The confinement spec for one run, or None when the run is not sandboxed.

    Paths are real paths (a granted root is never a symlink into a denied tree). The agent may write
    its working folder, a private per-job tmp and its own data/session folder; it reads the system
    and its own config but not the rest of the home folder; its config stays read-only so it cannot
    plant something a later run would load. See confine.py for the mechanism.
    """
    if not sandbox_wanted(harness, level_id):
        return None
    home = os.path.realpath(fsio.home())
    work = os.path.realpath(cwd)
    sbx = os.path.join(run_dir, "sbx")
    ro = list(_SANDBOX_SYS_RO)
    for part in exec_prefix:
        folder = os.path.realpath(os.path.dirname(part))
        if folder and folder not in ro:
            ro.append(folder)
    rw = [work, sbx]
    mkdir = []
    rw_files = list(_SANDBOX_DEV_FILES)
    predirs = [sbx]
    extra_env = {"TMPDIR": sbx, "npm_config_cache": os.path.join(sbx, "npm")}
    config = _xdg_dir(env, "XDG_CONFIG_HOME", ".config", home)
    data = _xdg_dir(env, "XDG_DATA_HOME", ".local/share", home)
    state = _xdg_dir(env, "XDG_STATE_HOME", ".local/state", home)
    cache = _xdg_dir(env, "XDG_CACHE_HOME", ".cache", home)
    if harness == "opencode":
        app = os.path.join(data, "opencode")
        locks = os.path.join(state, "opencode", "locks")
        claude_compat = os.path.join(sbx, "claude")
        # OpenCode's config, cache (which holds the plugins' own code) and state stay read-only; only
        # the lock files it makes under state are written. oh-my-openagent reads its settings from
        # ~/.omo and keeps Claude Code transcripts under CLAUDE_CONFIG_DIR, pointed here at the run's
        # private folder so ~/.claude, and the Claude sign-in in it, stay closed.
        rw += [app, locks]
        ro += [os.path.join(config, "opencode"), os.path.join(cache, "opencode"), os.path.join(state, "opencode"),
               os.path.join(home, ".omo")]
        predirs += [app, os.path.join(state, "opencode"), locks, os.path.join(cache, "opencode", "bin"),
                    os.path.join(sbx, "opencode"), claude_compat]
        extra_env["CLAUDE_CONFIG_DIR"] = claude_compat
    elif harness == "gemini":
        # SANDBOX=sandbox-exec keeps all of Gemini CLI's runtime state under the cache, so ~/.gemini
        # (settings, policies, extensions, the sign-in) stays read-only. A sign-in refresh cannot be
        # written back, so it simply runs again next job; the run itself still reads the sign-in.
        runtime = os.path.join(cache, ".gemini")
        rw.append(runtime)
        ro.append(os.path.join(home, ".gemini"))
        predirs.append(runtime)
        extra_env["SANDBOX"] = "sandbox-exec"
        if gemini_policy_wanted(level_id):
            # The plugin's own admin policy, and nothing else of the plugin: Gemini CLI reads it at
            # start, and without it the run stops (classify: policy_error) rather than go on unheld.
            ro.append(os.path.realpath(gemini_policy_path()))
    elif harness == "pi":
        # Pi's config folder is read-only except that proper-lockfile needs to make lock folders in
        # it; the session folder (set in the env) is writable. The sign-in stays readable but a
        # refresh is not written back (it runs again next job), so the folder keeps no new file.
        agent = os.path.join(home, ".pi", "agent")
        ro.append(os.path.join(home, ".pi"))
        mkdir.append(agent)
        session = _clean_abs(env.get("PI_CODING_AGENT_SESSION_DIR", ""))
        if session is not None:
            session = os.path.realpath(session)
            rw.append(session)
            predirs.append(session)
    return {"rw": rw, "ro": ro, "mkdir": mkdir, "rwFiles": rw_files, "preDirs": predirs, "env": extra_env}


def build_command(job, *, exec_prefix, run_dir, gen):
    """Exact agent argv, environment and cwd for one run (contract 3.6, v2 section 5)."""
    if not isinstance(gen, int) or isinstance(gen, bool) or gen < 1:
        raise ApError("bad_args")
    if _clean_abs(run_dir) is None:
        raise ApError("state_refused")
    built = _build(job, exec_prefix, run_dir, str(gen))
    return {"argv": built["argv"], "env": built["env"], "cwd": built["cwd"], "levelSlot": built["levelSlot"],
            "confine": built.get("confine")}


def display_argv(harness, argv, exec_len):
    """One-line form of an argv for the "Will run" line: CLI name, arguments, then <stdin>."""
    parts = [consts.CLI_NAMES.get(harness, "agent")]
    for arg in argv[exec_len:]:
        if arg == "":
            parts.append('""')
        elif any(ch.isspace() for ch in arg) or "'" in arg:
            parts.append(shlex.quote(arg))
        else:
            parts.append(arg)
    parts.append("<stdin>")
    return " ".join(parts)


def _inside_git(path):
    current = path
    for _ in range(_GIT_WALK_MAX):
        if os.path.lexists(os.path.join(current, ".git")):
            return True
        parent = os.path.dirname(current)
        if parent == current:
            return False
        current = parent
    return False


def preview_command(job):
    """Preview (contract 4.6) of what a run would execute with the CLI discovered now.

    Raises cli_missing or cli_untrusted when the CLI cannot be used; the fire-time fields
    (fireAt, immediate, fireAtHint, fireAtError) are left empty for the caller to fill, and
    cli_core adds the paid-usage gate.
    """
    harness = job["harness"]
    found = identity.discover_cli(harness)
    if not found["ok"]:
        raise ApError("cli_missing" if found["reason"] == "not_found" else "cli_untrusted")
    shown = dict(job)
    cli = dict(job.get("cli") or {})
    cli["link"] = found["link"]
    cli["real"] = found["real"]
    shown["cli"] = cli
    _entry, per = _level_entry(harness, job["level"])
    built = _build(shown, found["exec"], "<runs>", "<gen>", preview=True)
    warnings = []
    if harness == "codex" and job["target"].get("allowNonGit") is not True and not _inside_git(built["cwd"]):
        warnings.append("non_git_dir")
    return {
        "harness": harness,
        "level": job["level"],
        "mode": built["mode"],
        "display": display_argv(harness, built["argv"], len(found["exec"])),
        "argv": built["argv"],
        "env": dict(per["env"]),
        "cwd": built["cwd"],
        "binary": found["real"],
        "link": found["link"],
        "version": cli.get("version"),
        "levelCaption": per["caption"],
        "commandDigest": jobs.command_digest(shown),
        "fireAt": None,
        "immediate": False,
        "fireAtHint": None,
        "fireAtError": None,
        "warnings": warnings,
    }


def resume_display(job):
    """Terminal command that reopens the job's session, for "Copy resume command"."""
    harness = job["harness"]
    state = job.get("state") or {}
    sid = state.get("runSessionId") or job["target"].get("sessionId")
    if not isinstance(sid, str) or not _session_grammar(harness).fullmatch(sid):
        raise ApError("bad_status")
    cwd = job["target"].get("cwd")
    if _clean_abs(cwd) is None:
        raise ApError("bad_status")
    prefix = "cd " + shlex.quote(cwd) + " && "
    if harness == "claude":
        return prefix + "claude --resume " + sid
    if harness == "opencode":
        return prefix + "opencode --session " + sid
    if harness == "codex":
        return prefix + "codex resume " + sid
    if harness == "cursor":
        return prefix + consts.CLI_NAMES["cursor"] + " --resume " + sid
    if harness == "pi":
        path = effective_session_path(job)
        if not pi_session_path_ok(path):
            raise ApError("bad_status")
        return prefix + "pi --session " + shlex.quote(path)
    return prefix + "gemini --resume " + sid
